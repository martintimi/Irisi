export function getCountryByCodeOrName(identifier: string): AfricanCountry {
  if (!identifier) return AFRICAN_COUNTRIES[0];
  const query = identifier.trim().toLowerCase();
  const match = AFRICAN_COUNTRIES.find(
    (c) =>
      c.code.toLowerCase() === query ||
      c.name.toLowerCase() === query ||
      c.name.toLowerCase().includes(query)
  );
  return match || AFRICAN_COUNTRIES[0];
}

export function getStatesForCountry(countryNameOrCode: string): string[] {
  const country = getCountryByCodeOrName(countryNameOrCode);
  return country.states;
}
